/**
 * Canonical ChronoPay API error code taxonomy.
 *
 * This module is the single source of truth for every error code that exits
 * the API surface. Codes are organized as a discriminated union that
 * distinguishes:
 *
 * - **PUBLIC** codes (`scope: "public"`): a stable, versioned contract. Safe to
 *   expose to API clients. These never change HTTP status or semantics within
 *   a major version.
 * - **INTERNAL** codes (`scope: "internal"`): operational/diagnostic details
 *   used only in logging and internal handling. They are never exposed on the
 *   public API surface as-is (see `sendError`/`sendInternalError`).
 *
 * Messages are routed through i18n keys (`messageKey`) resolved by
 * `src/i18n/messageLoader.ts` at response time; code is stable contract,
 * message text is not.
 *
 * See `docs/error-codes.md` (regenerated by `npm run generate:error-docs`)
 * for the full documented table.
 */

export type I18nMessageKey = string & { readonly __brand: "I18nMessageKey" };

export function createMessageKey(key: string): I18nMessageKey {
  return key as I18nMessageKey;
}

