/**
 * Backward-compatible legacy map: `{ status, code }` per code.
 *
 * This preserves the historical `ERROR_CODES` surface consumed across the
 * codebase so existing call-sites migrate to `ERROR_TAXONOMY` incrementally.
 * The entries are derived from, and can never drift from, the taxonomy.
 */
export const ERROR_CODES: Record<ErrorCode, { code: string; status: number }> = Object.fromEntries(
  (Object.keys(ERROR_TAXONOMY) as ErrorCode[]).map((code) => [
    code,
    { code, status: ERROR_TAXONOMY[code].status },
  ]),
) as Record<ErrorCode, { code: string; status: number }>;

/**
 * Backward-compatible type aliases.
 * `ErrorCodeKey` is the union of every known code name; `ErrorCodeString` is
 * the union of every known code string — both equivalent to `ErrorCode`.
 */
export type ErrorCodeKey = ErrorCode;
export type ErrorCodeString = ErrorCode;
